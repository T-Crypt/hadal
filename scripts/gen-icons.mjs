// Regenerates HADAL's icons from the mark's geometry: the coverage mask in src/server/icon-mask.ts (which the
// server composites, it has no rasterizer) and the PNGs in web/ (icon-192, icon-512, icon-maskable-512,
// apple-touch-icon), drawn by src/server/icon-render.ts. The mark in web/icon.svg must stay the same drawing;
// this script checks it. Run from the repository root:
//
//   node scripts/gen-icons.mjs
import { deflateSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;

// The mark in 512-pixel space: the 32 × 32 drawing (uprights at x 8 and 24, the sounding line, the point of light)
// at scale 8 from the origin (128, 128). Strokes of width 20 (round caps), so each is a segment within 10 pixels.
const segments = [
    [
        [192, 168],
        [192, 344],
    ],
    [
        [320, 168],
        [320, 344],
    ],
    [
        [192, 224],
        [256, 296],
    ],
    [
        [256, 296],
        [320, 224],
    ],
];
const LIGHT = { x: 256, y: 340, r: 13.6 };

function distToSegment(px, py, [ax, ay], [bx, by]) {
    const dx = bx - ax;
    const dy = by - ay;
    const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)));

    return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}

const x0 = 181;
const y0 = 157;
const w = 150;
const h = 199;
const mask = Buffer.alloc(w * h);

for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
        const px = x0 + x + 0.5;
        const py = y0 + y + 0.5;
        let d = Infinity;

        for (const segment of segments) {
            d = Math.min(d, distToSegment(px, py, segment[0], segment[1]));
        }

        mask[y * w + x] = Math.round(Math.max(0, Math.min(1, 0.5 + (10 - d))) * 255);
    }
}

const b64 = deflateSync(mask).toString("base64");
const lines = [];

for (let i = 0; i < b64.length; i += 76) {
    lines.push(`        "${b64.slice(i, i + 76)}",`);
}

const ts = `/**
 * HADAL's mark as coverage (0 to 255), ${w} × ${h} pixels at 512-pixel scale, from the origin (${x0}, ${y0}) of
 * \`web/icon.svg\`'s 512 × 512 drawing: the three strokes, each within 10 pixels of its line. The point of light is
 * not in the mask; \`icon-render.ts\` draws it. Generated by \`scripts/gen-icons.mjs\`; the server has no rasterizer,
 * so it composites this instead.
 */
export const PI_MASK = {
    x: ${x0},
    y: ${y0},
    width: ${w},
    height: ${h},
    deflated: [
${lines.join("\n")}
    ].join(""),
};
`;

// The drawing of web/icon.svg is the same mark: its strokes and the point of light must agree with the numbers above.
const svg = readFileSync(join(ROOT, "web/icon.svg"), "utf8");
const svgPaths = [...svg.matchAll(/<path d="([^"]*)"/g)].map((each) => each[1]);
const expected = ["M192 168V344", "M320 168V344", "M192 224L256 296L320 224"];

for (const d of expected) {
    if (!svgPaths.includes(d)) {
        throw new Error(`web/icon.svg lost the stroke "${d}"`);
    }
}

if (
    !svg.includes(`cx="${LIGHT.x}"`) ||
    !svg.includes(`cy="${LIGHT.y}"`) ||
    !svg.includes(`r="${LIGHT.r}"`)
) {
    throw new Error(
        `web/icon.svg's point of light is no longer at (${LIGHT.x}, ${LIGHT.y}) r ${LIGHT.r}`,
    );
}

writeFileSync(join(ROOT, "src/server/icon-mask.ts"), ts);
console.log("icon-mask.ts written");

const { renderIcon, APP_ICON } = await import(join(ROOT, "src/server/icon-render.ts"));

writeFileSync(join(ROOT, "web/icon-512.png"), renderIcon(APP_ICON, 512));
writeFileSync(join(ROOT, "web/icon-192.png"), renderIcon(APP_ICON, 192));
writeFileSync(join(ROOT, "web/icon-maskable-512.png"), renderIcon(APP_ICON, 512, true));
writeFileSync(join(ROOT, "web/apple-touch-icon.png"), renderIcon(APP_ICON, 180));
console.log("PNGs written");
